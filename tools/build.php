<?php

/**
 * Assembles the deployable tree (what the web server serves) from the repository.
 *
 *   php tools/build.php --target=../deploy
 *   php tools/build.php --target=../deploy --dev      # development .env for local runs
 *   php tools/build.php --target=../deploy --keep     # keep existing var/ and .env
 *
 * The script never deletes a directory it does not own: it refuses to clean a
 * target unless the target contains the `.regru-build` marker or is empty.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$options = getopt('', ['target::', 'dev', 'keep', 'help']);

if (isset($options['help'])) {
    fwrite(STDOUT, "Usage: php tools/build.php [--target=deploy] [--dev] [--keep]\n");
    exit(0);
}

$targetName = (string) ($options['target'] ?? 'deploy');
$target = str_starts_with($targetName, '/') || preg_match('~^[A-Za-z]:[\\\\/]~', $targetName) === 1
    ? $targetName
    : $root . '/' . $targetName;
$isDev = isset($options['dev']);
$keep = isset($options['keep']);

if (!is_dir($target) && !mkdir($target, 0775, true) && !is_dir($target)) {
    fwrite(STDERR, "Cannot create target directory: {$target}\n");
    exit(1);
}

$marker = $target . '/.regru-build';
$entries = array_diff(scandir($target) ?: [], ['.', '..']);

if ($entries !== [] && !is_file($marker)) {
    fwrite(STDERR, "Refusing to clean {$target}: no .regru-build marker (not a build directory).\n");
    exit(1);
}

/**
 * @param array<string, string> $map source (relative) => destination (relative)
 */
function copyMap(string $root, string $target, array $map): void
{
    foreach ($map as $sourceRelative => $destinationRelative) {
        $source = $root . '/' . $sourceRelative;
        $destination = $target . '/' . $destinationRelative;

        if (!file_exists($source)) {
            fwrite(STDERR, "  ! missing: {$sourceRelative}\n");

            continue;
        }

        if (is_dir($source)) {
            $files = new RecursiveIteratorIterator(
                new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS),
                RecursiveIteratorIterator::SELF_FIRST,
            );

            foreach ($files as $file) {
                if (!$file instanceof SplFileInfo) {
                    continue;
                }

                $relative = substr($file->getPathname(), strlen($source));
                $path = $destination . $relative;

                if ($file->isDir()) {
                    if (!is_dir($path)) {
                        mkdir($path, 0775, true);
                    }
                } else {
                    if (!is_dir(dirname($path))) {
                        mkdir(dirname($path), 0775, true);
                    }

                    copy($file->getPathname(), $path);
                }
            }

            continue;
        }

        if (!is_dir(dirname($destination))) {
            mkdir(dirname($destination), 0775, true);
        }

        copy($source, $destination);
    }
}

// Preserve the database and .env when iterating on a local build.
$kept = [];

if ($keep) {
    foreach (['var', '.env'] as $preserve) {
        $source = $target . '/' . $preserve;

        if (file_exists($source)) {
            $backup = sys_get_temp_dir() . '/regru-keep-' . bin2hex(random_bytes(4)) . '-' . $preserve;
            $kept[$preserve] = $backup;
            rename($source, $backup);
        }
    }
}

// Clean previous build.
$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($target, FilesystemIterator::SKIP_DOTS),
    RecursiveIteratorIterator::CHILD_FIRST,
);

foreach ($iterator as $item) {
    if (!$item instanceof SplFileInfo) {
        continue;
    }

    $item->isDir() ? @rmdir($item->getPathname()) : @unlink($item->getPathname());
}

file_put_contents($marker, "Generated by tools/build.php; safe to delete.\n");

copyMap($root, $target, [
    'public/index.php' => 'index.php',
    'backend/autoload.php' => 'backend/autoload.php',
    'backend/bootstrap.php' => 'backend/bootstrap.php',
    'backend/config' => 'backend/config',
    'backend/migrations' => 'backend/migrations',
    'backend/resources' => 'backend/resources',
    'backend/src' => 'backend/src',
    'backend/bin' => 'backend/bin',
    'frontend/index.html' => 'frontend/index.html',
    'frontend/assets' => 'assets',
    'docs/openapi.yaml' => 'docs/openapi.yaml',
    '.env.example' => '.env.example',
]);

copy($root . '/frontend/assets/img/favicon.svg', $target . '/favicon.svg');

if (is_file($root . '/README.md')) {
    copy($root . '/README.md', $target . '/README.md');
}

foreach (['var', 'var/log', 'var/sessions', 'var/backups'] as $directory) {
    if (!is_dir($target . '/' . $directory)) {
        mkdir($target . '/' . $directory, 0775, true);
    }
}

$envPath = $target . '/.env';

if (!is_file($envPath) || $isDev) {
    $template = (string) file_get_contents($root . '/.env.example');
    $key = base64_encode(random_bytes(SODIUM_CRYPTO_SECRETBOX_KEYBYTES));

    $replacements = [
        'APP_KEY=' => 'APP_KEY=' . $key,
        'APP_URL=https://example.com/regru/' => $isDev ? 'APP_URL=http://127.0.0.1:8099' : 'APP_URL=https://example.com/regru/',
        'APP_DEBUG=0' => $isDev ? 'APP_DEBUG=1' : 'APP_DEBUG=0',
        'APP_ENV=production' => $isDev ? 'APP_ENV=development' : 'APP_ENV=production',
        'SESSION_SECURE=1' => $isDev ? 'SESSION_SECURE=0' : 'SESSION_SECURE=1',
    ];

    foreach ($replacements as $from => $to) {
        $template = str_replace($from, $to, $template);
    }

    file_put_contents($envPath, $template);
    @chmod($envPath, 0600);
    fwrite(STDOUT, '  .env created (' . ($isDev ? 'development' : 'production') . ")\n");
}

if ($kept !== []) {
    foreach ($kept as $name => $backup) {
        $destination = $target . '/' . $name;

        if (is_dir($destination)) {
            $cleanup = new RecursiveIteratorIterator(
                new RecursiveDirectoryIterator($destination, FilesystemIterator::SKIP_DOTS),
                RecursiveIteratorIterator::CHILD_FIRST,
            );

            foreach ($cleanup as $item) {
                if ($item instanceof SplFileInfo) {
                    $item->isDir() ? @rmdir($item->getPathname()) : @unlink($item->getPathname());
                }
            }

            @rmdir($destination);
        } elseif (is_file($destination)) {
            @unlink($destination);
        }

        rename($backup, $destination);
    }
}

$files = 0;
$bytes = 0;
$iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($target, FilesystemIterator::SKIP_DOTS));

foreach ($iterator as $file) {
    if ($file instanceof SplFileInfo && $file->isFile()) {
        $files++;
        $bytes += $file->getSize();
    }
}

fwrite(STDOUT, sprintf(
    "Built %s: %d files, %.1f KiB%s\n",
    $target,
    $files,
    $bytes / 1024,
    $isDev ? ' (development)' : '',
));
